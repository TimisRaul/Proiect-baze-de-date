CREATE TABLE CLIENT (
    ID_Client SERIAL PRIMARY KEY,
    Nume VARCHAR(50) NOT NULL,
    Prenume_Firma VARCHAR(100) NOT NULL,
    CNP_CUI VARCHAR(13) UNIQUE NOT NULL,
    Adresa VARCHAR(200),
    Telefon VARCHAR(15),
    Email VARCHAR(100)
);

CREATE TABLE AGENT (
    ID_Agent SERIAL PRIMARY KEY,
    Nume VARCHAR(50) NOT NULL,
    Prenume VARCHAR(50) NOT NULL,
    Cod_Licenta VARCHAR(20) UNIQUE NOT NULL,
    Telefon VARCHAR(15),
    Email VARCHAR(100),
    Procent_Comision DECIMAL(5,2) NOT NULL
);

CREATE TABLE TIP_ASIGURARE (
    ID_Tip SERIAL PRIMARY KEY,
    Denumire VARCHAR(100) NOT NULL,
    Descriere VARCHAR(255),
    Suma_Maxima_Acoperita DECIMAL(12,2) NOT NULL
);

CREATE TABLE EXPERT (
    ID_Expert SERIAL PRIMARY KEY,
    Nume VARCHAR(50) NOT NULL,
    Prenume VARCHAR(50) NOT NULL,
    Specializare VARCHAR(100) NOT NULL,
    Telefon VARCHAR(15),
    Email VARCHAR(100)
);

CREATE TABLE METODA_PLATA (
    ID_Metoda SERIAL PRIMARY KEY,
    Denumire VARCHAR(50) UNIQUE NOT NULL,
    Descriere VARCHAR(255),
    Necesita_Referinta BOOLEAN NOT NULL
);

CREATE TABLE UTILIZATOR (
    ID_Utilizator SERIAL PRIMARY KEY,
    Username VARCHAR(50) UNIQUE NOT NULL,
    Parola_Hash VARCHAR(255) NOT NULL,
    Rol VARCHAR(20) NOT NULL,
    ID_Agent INT UNIQUE REFERENCES AGENT(ID_Agent),
    ID_Client INT UNIQUE REFERENCES CLIENT(ID_Client),
    ID_Expert INT UNIQUE REFERENCES EXPERT(ID_Expert),
    Activ BOOLEAN NOT NULL,
    Data_Creare TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE POLITA (
    ID_Polita SERIAL PRIMARY KEY,
    Nr_Polita VARCHAR(20) UNIQUE NOT NULL,
    ID_Client INT NOT NULL REFERENCES CLIENT(ID_Client),
    ID_Agent INT NOT NULL REFERENCES AGENT(ID_Agent),
    ID_Tip INT NOT NULL REFERENCES TIP_ASIGURARE(ID_Tip),
    Data_Emiterii DATE NOT NULL,
    Data_Inceput DATE NOT NULL,
    Data_Expirarii DATE NOT NULL,
    Suma_Asigurata DECIMAL(12,2) NOT NULL,
    Prima_Asigurare DECIMAL(12,2) NOT NULL,
    Stare VARCHAR(20) NOT NULL
);

CREATE TABLE BUN_ASIGURAT (
    ID_Bun SERIAL PRIMARY KEY,
    ID_Polita INT NOT NULL REFERENCES POLITA(ID_Polita),
    Tip_Bun VARCHAR(50) NOT NULL,
    Descriere VARCHAR(255),
    Adresa_Locatie VARCHAR(200),
    Serie_Identificare VARCHAR(50),
    Valoare_Estimata DECIMAL(12,2) NOT NULL
);

CREATE TABLE BENEFICIAR (
    ID_Beneficiar SERIAL PRIMARY KEY,
    ID_Polita INT NOT NULL REFERENCES POLITA(ID_Polita),
    Nume VARCHAR(50) NOT NULL,
    Prenume VARCHAR(50) NOT NULL,
    CNP VARCHAR(13) NOT NULL,
    Relatie_cu_Asiguratul VARCHAR(50),
    Procent_Beneficiu DECIMAL(5,2) NOT NULL
);

CREATE TABLE COMISION (
    ID_Comision SERIAL PRIMARY KEY,
    ID_Polita INT UNIQUE NOT NULL REFERENCES POLITA(ID_Polita),
    Procent_Aplicat DECIMAL(5,2) NOT NULL,
    Suma_Comision DECIMAL(12,2) NOT NULL,
    Data_Calcul DATE NOT NULL,
    Stare_Plata VARCHAR(20) NOT NULL
);

CREATE TABLE DOSAR_DAUNA (
    ID_Dauna SERIAL PRIMARY KEY,
    ID_Polita INT NOT NULL REFERENCES POLITA(ID_Polita),
    ID_Expert INT NOT NULL REFERENCES EXPERT(ID_Expert),
    Data_Eveniment DATE NOT NULL,
    Data_Inregistrare DATE NOT NULL,
    Descriere VARCHAR(500) NOT NULL,
    Suma_Solicitata DECIMAL(12,2) NOT NULL,
    Suma_Aprobata DECIMAL(12,2),
    Stadiu VARCHAR(30) NOT NULL
);

CREATE TABLE DOCUMENT_DAUNA (
    ID_Document SERIAL PRIMARY KEY,
    ID_Dauna INT NOT NULL REFERENCES DOSAR_DAUNA(ID_Dauna),
    Nume_Fisier VARCHAR(150) NOT NULL,
    Tip_Document VARCHAR(50) NOT NULL,
    Cale_Fisier VARCHAR(255) NOT NULL,
    Data_Incarcare TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PLATA (
    ID_Plata SERIAL PRIMARY KEY,
    ID_Polita INT REFERENCES POLITA(ID_Polita),
    ID_Dauna INT REFERENCES DOSAR_DAUNA(ID_Dauna),
    ID_Metoda INT NOT NULL REFERENCES METODA_PLATA(ID_Metoda),
    Data_Platii DATE NOT NULL,
    Suma DECIMAL(12,2) NOT NULL,
    Tip_Plata VARCHAR(30) NOT NULL,
    Referinta_Bancara VARCHAR(50)
);

CREATE TABLE ISTORIC_STATUS_POLITA (
    ID_Istoric SERIAL PRIMARY KEY,
    ID_Polita INT NOT NULL REFERENCES POLITA(ID_Polita),
    Stare_Veche VARCHAR(20) NOT NULL,
    Stare_Noua VARCHAR(20) NOT NULL,
    Data_Ora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Motiv VARCHAR(255)
);

CREATE TABLE NOTIFICARE (
    ID_Notificare SERIAL PRIMARY KEY,
    ID_Client INT NOT NULL REFERENCES CLIENT(ID_Client),
    Canal VARCHAR(10) NOT NULL,
    Tip_Notificare VARCHAR(50) NOT NULL,
    Mesaj VARCHAR(500) NOT NULL,
    Data_Trimiterii TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Status VARCHAR(20) NOT NULL
);